async (page) => {
  if (new URL(page.url()).origin !== 'http://localhost:3058') throw Error('Use isolated F11 frontend');
  const results = [];
  const check = (name, condition) => { if (!condition) throw Error(name); results.push({ name, passed: true }); };
  const fixture = await page.evaluate(() => JSON.parse(localStorage.getItem('f11-fixture')));
  const targetId = fixture.ids[2];
  const read = id => page.evaluate(async id => {
    const response = await fetch('http://localhost:3057/areas/' + id, { headers: { Authorization: 'Bearer ' + localStorage.getItem('biblioteca-access-token') } });
    if (!response.ok) throw Error('Read ' + response.status); return response.json();
  }, id);
  const before = await read(targetId);
  const row = page.locator(`tr[data-page-id="${targetId}"]`);
  await row.getByRole('textbox', { name: 'Título de Estudo F11 02', exact: true }).fill('Estudo F11 02 revisado');
  await row.getByRole('textbox', { name: 'Categoria de Estudo F11 02', exact: true }).fill('Integração');
  await row.getByRole('combobox', { name: 'Nível de Estudo F11 02', exact: true }).selectOption('5');
  await row.getByRole('combobox', { name: 'Status de Estudo F11 02', exact: true }).selectOption('ESTUDADO');
  await row.getByRole('button', { name: 'Salvar propriedades', exact: true }).click();
  await row.getByRole('textbox', { name: 'Título de Estudo F11 02 revisado', exact: true }).waitFor();
  const saved = await read(targetId);
  check('Tabela altera propriedades com mesmo ID e nova revisão', saved.id === before.id && saved.updatedAt !== before.updatedAt && saved.nome === 'Estudo F11 02 revisado' && saved.categoria === 'Integração' && saved.nivelEntendimento === 5 && saved.subSection === 'ESTUDADO');
  await page.getByRole('combobox', { name: 'Visualização:', exact: true }).selectOption('BOARD');
  const card = page.locator(`article[data-page-id="${targetId}"]`);
  await card.waitFor();
  check('Quadro agrupa a mesma página no status salvo', await page.locator('.board-column').filter({ has: page.getByRole('heading', { name: /^Estudado \(/ }) }).locator(`[data-page-id="${targetId}"]`).count() === 1);
  await card.locator('summary').click();
  await card.getByRole('button', { name: 'Mover para Estudando', exact: true }).click();
  await page.locator('.board-column').filter({ has: page.getByRole('heading', { name: /^Estudando \(/ }) }).locator(`[data-page-id="${targetId}"]`).waitFor();
  check('Menu do quadro troca status persistido sem trocar ID', (await read(targetId)).subSection === 'ESTUDANDO');
  await card.getByRole('button', { name: 'Favoritar Estudo F11 02 revisado', exact: true }).click();
  await card.getByRole('button', { name: 'Desfavoritar Estudo F11 02 revisado', exact: true }).waitFor();
  check('Favoritar não registra abertura', (await read(targetId)).isFavorite && !(await read(targetId)).lastOpenedAt);
  await page.getByRole('button', { name: 'Próxima', exact: true }).click();
  await page.getByText('Página 2 de 2', { exact: true }).waitFor();
  await page.getByRole('combobox', { name: 'Visualização:', exact: true }).selectOption('TABLE');
  await page.getByText('Página 2 de 2', { exact: true }).waitFor();
  check('Trocar layout preserva paginação e ordenação', new URL(page.url()).searchParams.get('listPage') === '2' && new URL(page.url()).searchParams.get('order') === 'nome');
  await page.getByLabel('Categoria exata', { exact: true }).fill('Integração');
  await page.getByRole('combobox', { name: 'Nível mínimo', exact: true }).selectOption('0');
  await page.getByRole('button', { name: 'Aplicar filtros', exact: true }).click();
  await page.getByText('1 página', { exact: true }).waitFor();
  check('Filtro acontece antes da paginação e volta à primeira página', !new URL(page.url()).searchParams.has('listPage') && await page.locator('tbody tr').count() === 1 && await row.count() === 1);
  await page.getByRole('textbox', { name: 'Nome da visualização', exact: true }).fill('Revisão integrada F11');
  await page.getByRole('button', { name: 'Salvar como nova', exact: true }).click();
  await page.getByText('Visualização salva.', { exact: true }).waitFor();
  await page.reload(); await row.waitFor();
  await page.getByRole('combobox', { name: 'Visualização salva', exact: true }).selectOption({ label: 'Revisão integrada F11' });
  await page.getByRole('button', { name: 'Abrir visualização', exact: true }).click();
  await row.waitFor();
  check('Visualização nomeada reabre depois de recarga', new URL(page.url()).searchParams.get('categoria') === 'Integração' && new URL(page.url()).searchParams.get('minLevel') === '0');
  await page.getByRole('button', { name: 'Buscar páginas', exact: true }).click();
  await page.getByRole('textbox', { name: 'Buscar em toda a biblioteca', exact: true }).fill('Busca no corpo F11');
  await page.getByRole('button', { name: 'Próximos resultados', exact: true }).click();
  await page.getByText('Página 2 de 2', { exact: true }).waitFor();
  const resultButtons = page.locator('.library-search li button');
  await page.waitForFunction(() => document.querySelectorAll('.library-search li button').length === 6);
  check('Busca global no corpo alcança resultados além dos primeiros 20', await resultButtons.count() === 6);
  const resultName = await resultButtons.first().innerText();
  await resultButtons.first().click();
  await page.getByRole('textbox', { name: 'Conteúdo da página', exact: true }).waitFor();
  const openedId = new URL(page.url()).searchParams.get('page');
  const opened = await read(openedId);
  check('Busca abre o documento pelo ID original', fixture.ids.includes(openedId) && opened.nome === resultName);
  if (!(await page.getByRole('link', { name: 'Recentes', exact: true }).isVisible())) await page.getByRole('button', { name: 'Navegação', exact: true }).first().click();
  await page.getByRole('link', { name: 'Recentes', exact: true }).click();
  await page.getByRole('heading', { name: 'Recentes', exact: true }).waitFor();
  await page.getByRole('heading', { name: resultName, exact: true }).waitFor();
  check('Recentes contém a página realmente aberta', Boolean((await read(openedId)).lastOpenedAt));


  return results;
}
